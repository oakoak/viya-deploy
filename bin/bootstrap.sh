#!/usr/bin/env bash
# Однократная установка инструмента aml-deploy на машине (сервер или dev).
# Создаёт venv в <tool>/venv, ставит рантайм-зависимости (офлайн из wheels/ если он есть,
# иначе online), и запоминает корень custom_config в bin/aml-deploy.config.
#
# Usage: bin/bootstrap.sh <custom_config_root>
#   <custom_config_root>  каталог custom_config на сервере (aml-deploy.env, build/, симлинк current),
#                         напр. /opt/sas/aml3/custom_config.
#                         Спецзначение '-'  => dev-режим: config не пишется (доступна `build`,
#                         деплой требует явного --custom-config-root/--env-file).
#
# Офлайн-сервер (нет доступа в PyPI): заранее наполните <tool>/wheels/ (см. requirements.txt,
# команда `pip download ...`), тогда установка пойдёт без сети.
set -euo pipefail

BIN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOL_DIR="$(dirname "$BIN_DIR")"
VENV="$TOOL_DIR/venv"
WHEELS="$TOOL_DIR/wheels"
REQ="$TOOL_DIR/requirements.txt"

if [ "$#" -lt 1 ]; then
  echo "Usage: $0 <custom_config_root>   (или '-' для dev-режима без деплоя)" >&2
  exit 2
fi
CUSTOM_CONFIG_ROOT="$1"

PY=""
for cand in python3.8 python3 python; do
  if command -v "$cand" >/dev/null 2>&1; then PY="$cand"; break; fi
done
[ -n "$PY" ] || { echo "bootstrap: не найден python3" >&2; exit 1; }
"$PY" - <<'PYEOF' || { echo "bootstrap: требуется Python >= 3.8" >&2; exit 1; }
import sys
sys.exit(0 if sys.version_info[:2] >= (3, 8) else 1)
PYEOF
echo "bootstrap: python = $("$PY" --version 2>&1); tool = $TOOL_DIR"

if [ ! -x "$VENV/bin/python" ]; then
  echo "bootstrap: создаю venv -> $VENV"
  "$PY" -m venv "$VENV"
fi
VPY="$VENV/bin/python"

if [ -d "$WHEELS" ] && ls "$WHEELS"/*.whl >/dev/null 2>&1; then
  echo "bootstrap: офлайн-установка зависимостей из $WHEELS"
  "$VPY" -m pip install --no-index --find-links "$WHEELS" -r "$REQ"
else
  echo "bootstrap: wheels/ пуст — онлайн-установка из PyPI (для офлайн-сервера сначала наполните wheels/)"
  "$VPY" -m pip install -r "$REQ"
fi

CONFIG_FILE="$BIN_DIR/aml-deploy.config"

if [ "$CUSTOM_CONFIG_ROOT" = "-" ]; then
  rm -f "$CONFIG_FILE"
  echo "bootstrap: dev-режим — $CONFIG_FILE не создан (для деплоя укажите корень явно)"
else
  [ -d "$CUSTOM_CONFIG_ROOT" ] || { echo "bootstrap: каталог не найден: $CUSTOM_CONFIG_ROOT" >&2; exit 1; }
  CUSTOM_CONFIG_ROOT="$(cd "$CUSTOM_CONFIG_ROOT" && pwd)"
  printf '# generated by bootstrap.sh — do not edit by hand\nCUSTOM_CONFIG_ROOT=%q\n' \
    "$CUSTOM_CONFIG_ROOT" > "$CONFIG_FILE"
  echo "bootstrap: custom_config root = $CUSTOM_CONFIG_ROOT -> $CONFIG_FILE"
fi

echo "bootstrap: smoke-тест запуска..."
PYTHONPATH="$TOOL_DIR/src" "$VPY" -m amldeploy --help >/dev/null
echo "bootstrap: OK. Дальше: $BIN_DIR/aml-deploy <команда>  (list | switch | release | deploy | build)"
